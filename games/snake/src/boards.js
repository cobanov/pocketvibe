// blocks: 1 for every cell with a block, row by row.
export const BOARDS = LAYOUTS.map(({ id, name, rows }) => {
  const blocks = new Uint8Array(COLS * ROWS);
  for (let z = 0; z < rows.length; z++) {
    for (let x = 0; x < COLS; x++) if (rows[z][x] === '#') blocks[z * COLS + x] = 1;
  }
  return { id, name, blocks };
});
